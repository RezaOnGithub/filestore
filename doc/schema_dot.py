#!/usr/bin/env python3
"""Generate doc/SCHEMA.dot from crates/filestore/src/schema.sql.

Columns, primary keys, single-column uniqueness, nullability, and foreign
keys are read from the DDL itself (loaded into an in-memory SQLite database),
so the diagram cannot drift from the schema. Grouping, colors, table notes,
and logical references (columns that refer to rows without a declared foreign
key) are listed below; update them when tables are added.

Usage:  python3 doc/schema_dot.py > doc/SCHEMA.dot
Render: dot -Tsvg doc/SCHEMA.dot -o SCHEMA.svg   (output is not kept in the repository)
"""

import sqlite3
import sys
from pathlib import Path

SCHEMA = Path(__file__).resolve().parent.parent / "crates/filestore/src/schema.sql"

# (key, header color, subtitle color, legend label, [(table, note)])
GROUPS = [
    ("scan", "#1E40AF", "#DBEAFE", "catalog, epochs, locations, scans", [
        ("meta", "key/value: schema version, root path, settings"),
        ("epochs", "immutable · active epoch = latest row"),
        ("locations", "immutable · interned root-relative byte paths"),
        ("scans", "request + session · closed once; then immutable"),
        ("diagnostics", "append-only while the scan runs"),
    ]),
    ("obs", "#0F766E", "#CCFBF1", "observations and listings", [
        ("observations", "append-only while the scan runs"),
        ("enumerations", "one listing attempt · append-only"),
        ("enumeration_results", "terminal result · closes the attempt"),
    ]),
    ("read", "#15803D", "#DCFCE7", "reads, Blobs, baselines", [
        ("reads", "one read attempt · opened observation fixed at insert"),
        ("read_results", "terminal result · content and location outcomes"),
        ("blobs", "exact content · digest private · retained"),
        ("sampling_policies", "versioned policy encoding · immutable"),
        ("baselines", "sample token per Blob and policy · private"),
    ]),
    ("meta", "#B45309", "#FEF3C7", "derived metadata and command acceptance", [
        ("derived_metadata", "extractor output · UNIQUE(blob, extractor, version, config)"),
        ("action_provenance", "reviewed advisor proposal behind an action"),
        ("command_ledger", "idempotent request IDs · result replayed on retry"),
    ]),
    ("proj", "#0E7490", "#CFFAFE", "projection (rebuildable)", [
        ("occurrences", "derived per location · UNIQUE(epoch, location) while current"),
    ]),
    ("sem", "#7C3AED", "#EDE9FE", "semantic records", [
        ("semantic_ops", "append-only operation log · changes as JSON"),
        ("tag_hierarchies", "exclusive tag tree"),
        ("tags", "UNIQUE(hierarchy, parent, name)"),
        ("tag_assignments", "one tag per target and hierarchy"),
        ("lineages", "tombstoned, never deleted"),
        ("revisions", "content identity immutable"),
        ("revision_parents", "DAG within one Lineage"),
    ]),
]

# Logical references without a foreign key: (table, column, target table, target column, label)
LOGICAL = [
    ("occurrences", "first_obs_id", "observations", "id", None),
    ("occurrences", "last_obs_id", "observations", "id", None),
    ("occurrences", "content_read_id", "reads", "id", None),
    ("occurrences", "verified_read_id", "reads", "id", None),
    ("occurrences", "check_read_id", "reads", "id", None),
    ("occurrences", "issue_read_id", "reads", "id", None),
    ("occurrences", "check_blob_id", "blobs", "id", None),
    ("occurrences", "prev_blob_id", "blobs", "id", None),
    ("occurrences", "listing_enum_id", "enumerations", "id", None),
    ("tag_assignments", "target_id", "blobs", "id", "target_kind = blob"),
    ("tag_assignments", "target_id", "lineages", "id", "lineage"),
    ("tag_assignments", "target_id", "revisions", "id", "revision"),
]


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def main():
    db = sqlite3.connect(":memory:")
    db.executescript(SCHEMA.read_text())
    declared = {r[0] for r in db.execute("SELECT name FROM sqlite_schema WHERE type = 'table'")}
    grouped = {t for _, _, _, _, tables in GROUPS for t, _ in tables}
    missing = declared - grouped
    if missing:
        sys.exit(f"schema_dot.py: tables without a group: {', '.join(sorted(missing))}")

    out = []
    w = out.append
    legend = "   ".join(f'<FONT COLOR="{c}"><B>■</B> {esc(label)}</FONT>' for _, c, _, label, _ in GROUPS)
    w("// Filestore prototype schema: the tables of crates/filestore/src/schema.sql.")
    w("// Generated by doc/schema_dot.py; regenerate after schema changes instead of editing by hand.")
    w("// Render with: dot -Tsvg doc/SCHEMA.dot -o SCHEMA.svg (the output is not kept in the repository)")
    w("")
    w("digraph filestore_schema {")
    w("  graph [")
    w('    rankdir=LR, bgcolor="#F8FAFC", pad="0.4", nodesep="0.35", ranksep="1.1",')
    w('    splines=spline, outputorder=edgesfirst, fontname="Helvetica", labelloc=t, labeljust=l,')
    w('    label=<<FONT POINT-SIZE="24"><B>Filestore prototype schema</B></FONT><BR/>'
      '<FONT POINT-SIZE="10" COLOR="#475569">crates/filestore/src/schema.sql · SQLite STRICT tables · '
      'arrows point from referencing column to referenced row · dashed = logical reference without FK · '
      '<FONT COLOR="#94A3B8">?</FONT> nullable · triggers enforce closure and immutability of evidence '
      '(see the notes under each table)</FONT><BR/>'
      f'<FONT POINT-SIZE="11">{legend}</FONT><BR/> >')
    w("  ];")
    w("")
    w('  node [shape=plain, fontname="Helvetica", fontsize=9];')
    w('  edge [color="#94A3B8", penwidth=1.0, arrowsize=0.6, arrowhead=vee, fontname="Helvetica"];')

    color_of = {}
    for key, color, light, label, tables in GROUPS:
        w("")
        w(f"  // {label}")
        for table, note in tables:
            color_of[table] = color
            cols = db.execute(f"PRAGMA table_info({table})").fetchall()
            fks = {r[3]: r[2] for r in db.execute(f"PRAGMA foreign_key_list({table})")}
            unique = set()
            for idx in db.execute(f"PRAGMA index_list({table})"):
                name, is_unique, partial = idx[1], idx[2], idx[4]
                info = db.execute(f"PRAGMA index_info({name})").fetchall()
                if is_unique and not partial and len(info) == 1 and info[0][2] is not None:
                    unique.add(info[0][2])
            pk_cols = [c[1] for c in cols if c[5] > 0]
            w(f'  {table} [label=<<TABLE BORDER="0" CELLBORDER="1" CELLSPACING="0" COLOR="#64748B" BGCOLOR="white">')
            w(f'    <TR><TD BGCOLOR="{color}" ALIGN="LEFT" CELLPADDING="6"><FONT COLOR="white" POINT-SIZE="12">'
              f'<B>{table}</B></FONT><BR/><FONT COLOR="{light}" POINT-SIZE="8">{esc(note)}</FONT></TD></TR>')
            for _, name, ctype, notnull, _, pk in cols:
                marks = []
                if pk:
                    marks.append('<FONT COLOR="#B45309">PK</FONT>')
                if name in unique and not (pk and len(pk_cols) == 1):
                    marks.append('<FONT COLOR="#7C3AED">UQ</FONT>')
                if name in fks:
                    marks.append('<FONT COLOR="#2563EB">FK</FONT>')
                nullable = ' <FONT COLOR="#94A3B8">?</FONT>' if not notnull and not pk else ""
                title = f"<B>{name}</B>" if pk else name
                kind = f' <FONT COLOR="#94A3B8" POINT-SIZE="8">{ctype.lower()}</FONT>' if ctype else ""
                suffix = f"  {' '.join(marks)}" if marks else ""
                w(f'    <TR><TD PORT="{name}" ALIGN="LEFT" CELLPADDING="3">{title}{kind}{nullable}{suffix}</TD></TR>')
            w("  </TABLE>>];")

    w("")
    w("  // Foreign keys")
    for _, _, _, _, tables in GROUPS:
        for table, _ in tables:
            for fk in db.execute(f"PRAGMA foreign_key_list({table})"):
                target, col, tcol = fk[2], fk[3], fk[4] or "id"
                w(f'  {table}:{col} -> {target}:{tcol} [color="{color_of[table]}80"];')
    w("")
    w("  // Logical references")
    for table, col, target, tcol, label in LOGICAL:
        attrs = f'color="{color_of[table]}80", style=dashed'
        if label:
            attrs += f', label="{label}", fontsize=8, fontcolor="#64748B"'
        w(f"  {table}:{col} -> {target}:{tcol} [{attrs}];")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
